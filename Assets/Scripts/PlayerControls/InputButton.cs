namespace PlayerControls
{
    /// <summary>
    /// Enum representing different input buttons.
    /// </summary>
	public enum InputButton
	{
        /// <summary>
        /// No button.
        /// </summary>
		None,

        /// <summary>
        /// Left mouse button.
        /// </summary>
		LeftMouse,

        /// <summary>
        /// Right mouse button.
        /// </summary>
		RightMouse,

        /// <summary>
        /// Middle mouse button.
        /// </summary>
		MiddleMouse,

        /// <summary>
        /// Count of input buttons.
        /// </summary>
		Count
	}
}
